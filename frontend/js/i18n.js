/**
 * Get current language from localStorage (default: English).
 */
function getCurrentLang() {
    return localStorage.getItem('temple_lang') || 'en';
}

/**
 * Set language and update all translatable elements.
 * @param {string} lang - 'en' or 'kn'
 */
function setLanguage(lang) {
    localStorage.setItem('temple_lang', lang);
    document.body.setAttribute('data-lang', lang);

    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translations[lang][key];
            } else if (el.tagName === 'OPTION') {
                el.textContent = translations[lang][key];
            } else {
                el.textContent = translations[lang][key];
            }
        }
    });

    // Update lang toggle button text
    const toggleBtn = document.getElementById('lang-toggle');
    if (toggleBtn) {
        toggleBtn.textContent = translations[lang].lang_switch;
    }

    // Set font family based on language
    if (lang === 'kn') {
        document.body.style.fontFamily = "'Noto Sans Kannada', sans-serif";
    } else {
        document.body.style.fontFamily = "'Poppins', sans-serif";
    }

    // Notify pages/components of language change
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

/**
 * Get a translation string by key.
 * @param {string} key - Translation key
 * @returns {string} Translated string
 */
function t(key) {
    const lang = getCurrentLang();
    return (translations[lang] && translations[lang][key]) || key;
}

/**
 * Toggle between English and Kannada.
 */
function toggleLanguage() {
    const current = getCurrentLang();
    const next = current === 'en' ? 'kn' : 'en';
    setLanguage(next);
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
    setLanguage(getCurrentLang());
});
